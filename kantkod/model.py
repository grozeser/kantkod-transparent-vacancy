THRESHOLDS = {"duties": 0.55, "requirements": 0.56, "schedule": 0.52, "pay": 0.53, "workplace": 0.53, "employment": 0.54}


def feature_text(topic, text):
    return f"{topic} {normal(text)}"


def version_id():
    fingerprint = hashlib.sha256(inspect.getsource(feature_text).encode())
    fingerprint.update(inspect.getsource(ClarityModel).encode())
    fingerprint.update(repr((TRAINING, THRESHOLDS, version("scikit-learn"))).encode())
    return "tfidf-logreg-" + fingerprint.hexdigest()[:12]


class ClarityModel:
    def __init__(self):
        from sklearn.feature_extraction.text import TfidfVectorizer
        from sklearn.linear_model import LogisticRegression
        from sklearn.pipeline import FeatureUnion, make_pipeline

        examples, labels = [], []
        for topic, (ambiguous, specific) in TRAINING.items():
            for label, rows in ((1, ambiguous), (0, specific)):
                examples.extend(feature_text(topic, row) for row in rows)
                labels.extend([label] * len(rows))
        self.pipeline = make_pipeline(
            FeatureUnion([
                ("words", TfidfVectorizer(ngram_range=(1, 2), sublinear_tf=True)),
                ("characters", TfidfVectorizer(analyzer="char_wb", ngram_range=(3, 5), sublinear_tf=True)),
            ], transformer_weights={"words": 0.65, "characters": 1.0}),
            LogisticRegression(C=8, class_weight="balanced", max_iter=400, random_state=42),
        )
        self.pipeline.fit(examples, labels)

    def scores(self, candidates):
        if not candidates:
            return []
        texts = [feature_text(topic, text) for topic, text in candidates]
        return self.pipeline.predict_proba(texts)[:, 1]

    @staticmethod
    def threshold(topic):
        return THRESHOLDS[topic]
